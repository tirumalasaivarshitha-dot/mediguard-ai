export function daysSince(isoDate: string) {
  return Math.max(0, Math.round((Date.now() - new Date(isoDate).getTime()) / 86400000))
}

function seriesFor(eq: Equipment, n = 48): TelemetryPoint[] {
  const baseTemp =
    eq.equipmentType === 'MRI Scanner' ? 22 : eq.equipmentType === 'Ventilator' ? 31 : 24
  const stress = (100 - eq.healthScore) / 100
  const points: TelemetryPoint[] = []
  for (let i = n - 1; i >= 0; i--) {
    const t = new Date(Date.now() - i * 60000).toISOString()
    const drift = stress * (n - i) * 0.08
    points.push({
      timestamp: t,
      temperature: Number((baseTemp + drift + Math.sin(i / 6) * (1 + stress * 3)).toFixed(1)),
      vibration: Number((0.6 + stress * 2.4 + Math.cos(i / 5) * 0.2).toFixed(2)),
      powerKw: Number(
        ((eq.equipmentType.includes('Scanner') ? 12 : 0.6) + stress * 3 + Math.sin(i / 8) * 0.4).toFixed(2),
      ),
      pressure: Number((eq.equipmentType === 'Ventilator' ? 18 + stress * 22 : 4 + stress * 2).toFixed(1)),
      voltage: eq.equipmentType.includes('Scanner') ? 400 : 230,
      errorCount: Math.max(0, Math.round(stress * 12 + (i < 6 ? stress * 4 : 0))),
      operatingHours: eq.operatingHours + Math.round((n - i) / 12),
    })
  }
  return points
}

